import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { serializeGeneratedCodeString } from "./generated-code-string.mjs";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalogPath = resolve(
  repositoryRoot,
  "src/shared/code-languages/code-language-catalog-v1.json",
);
const bundlePath = resolve(
  repositoryRoot,
  "third_party/blocknote/packages/code-block/src/shiki.bundle.ts",
);

const catalog = JSON.parse(await readFile(catalogPath, "utf8"));
if (catalog.contractVersion !== 1 || !Array.isArray(catalog.languages)) {
  throw new TypeError("Unsupported code language catalog");
}

const loaderByLanguageId = new Map();
const productLanguageIdsByShikiLanguage = new Map();
const LANGUAGE_TOKEN_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u;

const readLanguageToken = (value, field) => {
  if (typeof value !== "string" || !LANGUAGE_TOKEN_PATTERN.test(value)) {
    throw new TypeError(`${field} must be a lowercase kebab-case language token`);
  }
  return value;
};

for (const language of catalog.languages) {
  const languageId = readLanguageToken(language.id, "Code language id");
  if (language.shikiLanguage === null) continue;
  const shikiLanguage = readLanguageToken(language.shikiLanguage, `${languageId}.shikiLanguage`);
  if (loaderByLanguageId.has(languageId)) {
    throw new TypeError(`Duplicate highlighted code language id: ${languageId}`);
  }
  loaderByLanguageId.set(languageId, shikiLanguage);
  const productLanguageIds = productLanguageIdsByShikiLanguage.get(shikiLanguage) ?? [];
  productLanguageIds.push(languageId);
  productLanguageIdsByShikiLanguage.set(shikiLanguage, productLanguageIds);
}

// Grammar names are the highlighting contract. Product IDs may be aliases, but
// must never shadow another grammar (JavaScript/JSX and Flow share this boundary).
const loaders = new Map(
  [...productLanguageIdsByShikiLanguage.keys()].map((grammar) => [grammar, grammar]),
);
for (const [languageId, grammar] of loaderByLanguageId) {
  if (!loaders.has(languageId)) loaders.set(languageId, grammar);
}

const languageLoaders = [...loaders]
  .map(([languageId, shikiLanguage]) => {
    const productAliases = productLanguageIdsByShikiLanguage
      .get(shikiLanguage)
      .filter(
        (productLanguageId) =>
          productLanguageId !== shikiLanguage &&
          !productLanguageIdsByShikiLanguage.has(productLanguageId),
      );
    const modulePath = serializeGeneratedCodeString(`@shikijs/langs-precompiled/${shikiLanguage}`);
    if (productAliases.length === 0) {
      return `  ${serializeGeneratedCodeString(languageId)}: () => import(${modulePath}),`;
    }
    return `  ${serializeGeneratedCodeString(languageId)}: () => import(${modulePath}).then((module) => ({
    default: module.default.map((language) =>
      language.name === ${serializeGeneratedCodeString(shikiLanguage)}
        ? { ...language, aliases: [...new Set([...(language.aliases ?? []), ${productAliases
          .map(serializeGeneratedCodeString)
          .join(", ")}])] }
        : language,
    ),
  })),`;
  })
  .join("\n");

const source = `/* Generated by scripts/generate-code-language-artifacts.mjs. */
import type {
  DynamicImportLanguageRegistration,
  HighlighterGeneric,
  ThemeRegistration,
} from "@shikijs/types";
import { createBundledHighlighter } from "@shikijs/core";
import { createJavaScriptRegexEngine } from "@shikijs/engine-javascript";

const bundledLanguages = {
${languageLoaders}
} as const satisfies Record<string, DynamicImportLanguageRegistration>;

type BundledLanguage = keyof typeof bundledLanguages;
type Highlighter = HighlighterGeneric<BundledLanguage, string>;

/** Grammars only: the product supplies its code theme as a registration. */
export const createHighlighter = /* @__PURE__ */ createBundledHighlighter<BundledLanguage, string>({
  langs: bundledLanguages,
  themes: {},
  engine: () => createJavaScriptRegexEngine(),
}) as (options?: {
  themes?: ThemeRegistration[];
  langs?: BundledLanguage[];
}) => Promise<Highlighter>;
`;

await writeFile(bundlePath, source, "utf8");
console.log(
  `Generated ${loaderByLanguageId.size} highlighted languages from ${catalog.languages.length} product languages.`,
);
