import { readFileSync } from "node:fs";
import { basename } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { parseTypeScriptSource } from "../lib/oxc-source";
import { MOBILE_ICON_COMPONENTS, LOCAL_MOBILE_GLYPHS } from "./mapping";
import { extractIcon } from "./extract";
import type { IconGlyph } from "../../packages/mobile/src/ui/icon-glyphs";

export const REGENERATE_COMMAND = "vp run mobile:icons:generate";
export const GENERATED_PATH = "packages/mobile/src/ui/icon-glyphs.generated.ts";

/** Render the actual desktop components; no desktop geometry is copied into the phone sources. */
export function generateMobileIcons() {
  const glyphs: Record<string, IconGlyph> = {};
  const sources: Record<string, string> = {};
  const imports = parseTypeScriptSource(
    "mapping.ts",
    readFileSync(new URL("./mapping.ts", import.meta.url), "utf8"),
  ).body.filter((node) => node.type === "ImportDeclaration");
  const files = new Map(
    imports.flatMap((node) =>
      node.specifiers.map(
        (specifier) => [specifier.local.name, `${basename(node.source.value)}.tsx`] as const,
      ),
    ),
  );
  for (const [name, entry] of Object.entries(MOBILE_ICON_COMPONENTS)) {
    if (Object.keys(entry).length !== 1) throw new Error(`${name}: expected one desktop component`);
    const [source] = Object.keys(entry);
    const [component] = Object.values(entry);
    if (!source || !component) throw new Error(`${name}: expected one desktop component`);
    const file = files.get(source);
    if (!file) throw new Error(`${name}: missing source import for ${source}`);
    try {
      glyphs[name] = extractIcon(name, renderToStaticMarkup(createElement(component))).glyph;
      sources[name] = `${source} · ${file}`;
    } catch (error) {
      throw new Error(
        `${name} (${source}): ${error instanceof Error ? error.message : String(error)}`,
        { cause: error },
      );
    }
  }
  for (const [name, glyph] of Object.entries(LOCAL_MOBILE_GLYPHS)) {
    if (name in glyphs) throw new Error(`${name}: local glyph shadows a desktop mapping`);
    glyphs[name] = glyph;
    sources[name] = "local glyph";
  }
  return { glyphs, sources };
}

export function mobileIconModule({ glyphs }: ReturnType<typeof generateMobileIcons>): string {
  return `// Generated by \`${REGENERATE_COMMAND}\`. Edit scripts/mobile-icons/mapping.ts instead.\nimport type { IconGlyph } from "./icon-glyphs";\n\nexport const ICON_GLYPHS = ${JSON.stringify(glyphs, null, 2)} as const satisfies Record<string, IconGlyph>;\n\nexport type IconName = keyof typeof ICON_GLYPHS;\n`;
}
