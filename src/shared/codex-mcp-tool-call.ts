function asRecord(value: unknown): Record<string, unknown> | null {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return null;
  return value as Record<string, unknown>;
}

function optionalString(record: Record<string, unknown>, key: string): string | undefined {
  const value = record[key];
  return typeof value === "string" ? value : undefined;
}

function normalizeAnnotations(value: unknown): CodexMcpToolCallAnnotations | undefined {
  const record = asRecord(value);
  if (!record) return undefined;

  const rawAudience = record.audience;
  const audience =
    Array.isArray(rawAudience) &&
    rawAudience.length > 0 &&
    rawAudience.every((entry) => entry === "assistant" || entry === "user")
      ? ([...rawAudience] as Array<"assistant" | "user">)
      : undefined;
  const priority =
    typeof record.priority === "number" && Number.isFinite(record.priority)
      ? record.priority
      : undefined;
  const lastModified = typeof record.lastModified === "string" ? record.lastModified : undefined;

  if (audience === undefined && priority === undefined && lastModified === undefined) {
    return undefined;
  }

  const annotations: CodexMcpToolCallAnnotations = {};
  if (audience !== undefined || "audience" in record) {
    annotations.audience = audience;
  }
  if (priority !== undefined || "priority" in record) {
    annotations.priority = priority;
  }
  if (lastModified !== undefined || "lastModified" in record) {
    annotations.lastModified = lastModified;
  }
  return annotations;
}

function normalizeEmbeddedResource(
  value: unknown,
): Extract<CodexMcpToolCallContentBlock, { type: "embedded_resource" }> | null {
  const record = asRecord(value);
  if (!record || typeof record.uri !== "string") return null;

  return {
    type: "embedded_resource",
    resource: {
      uri: record.uri,
      name: optionalString(record, "name"),
      title: optionalString(record, "title"),
      description: optionalString(record, "description"),
      mimeType: optionalString(record, "mimeType"),
      text: optionalString(record, "text"),
      blob: optionalString(record, "blob"),
      annotations: normalizeAnnotations(record.annotations),
    },
  };
}

export function normalizeCodexMcpToolCallContentBlock(
  value: ProtocolMcpToolCallResult["content"][number],
): CodexMcpToolCallContentBlock {
  const record = asRecord(value);
  if (!record || typeof record.type !== "string") {
    return { type: "unknown", raw: value };
  }

  const annotations = normalizeAnnotations(record.annotations);
  switch (record.type) {
    case "text":
      if (typeof record.text !== "string") return { type: "unknown", raw: value };
      return { type: "text", text: record.text, annotations };

    case "image":
      if (typeof record.data !== "string" || typeof record.mimeType !== "string") {
        return { type: "unknown", raw: value };
      }
      return {
        type: "image",
        data: record.data,
        mimeType: record.mimeType,
        annotations,
      };

    case "audio":
      if (typeof record.data !== "string" || typeof record.mimeType !== "string") {
        return { type: "unknown", raw: value };
      }
      return {
        type: "audio",
        data: record.data,
        mimeType: record.mimeType,
        annotations,
      };

    case "resource_link":
      if (typeof record.uri !== "string") return { type: "unknown", raw: value };
      return {
        type: "resource_link",
        uri: record.uri,
        name: optionalString(record, "name"),
        title: optionalString(record, "title"),
        description: optionalString(record, "description"),
        mimeType: optionalString(record, "mimeType"),
        annotations,
      };

    case "embedded_resource":
    case "resource": {
      const embeddedResource = normalizeEmbeddedResource(record.resource);
      return embeddedResource ?? { type: "unknown", raw: value };
    }

    default:
      return { type: "unknown", raw: value };
  }
}

export function projectCodexMcpToolCallResult(
  result: ProtocolMcpToolCallResult | null,
  error: ProtocolMcpToolCallError | null,
): CodexMcpToolCallNormalizedResult {
  if (!result && !error) return null;

  if (error) {
    return {
      type: "error",
      kind: "protocol",
      error: error.message,
      rawError: error,
    };
  }

  if (!result) return null;

  return {
    type: "success",
    content: result.content.map(normalizeCodexMcpToolCallContentBlock),
    structuredContent: result.structuredContent,
    raw: result,
  };
}

function normalizeComputerUseApp(
  value: unknown,
): Extract<CodexMcpToolCallSource, { kind: "computerUse" }>["app"] | undefined {
  if (value === null) return null;

  const record = asRecord(value);
  if (!record) return undefined;
  if (record.kind === "appId" && typeof record.appId === "string" && record.appId.length > 0) {
    return { kind: "appId", appId: record.appId };
  }
  if (
    record.kind === "displayName" &&
    typeof record.displayName === "string" &&
    record.displayName.length > 0
  ) {
    return { kind: "displayName", displayName: record.displayName };
  }
  return undefined;
}

function detectMcpVisualSourcePlatform(): CodexMcpVisualSourcePlatform {
  const platform = typeof navigator === "undefined" ? "" : (navigator.platform ?? "");
  if (platform.startsWith("Mac")) return "macOS";
  if (platform.startsWith("Win")) return "windows";
  return "linux";
}

function normalizeSourceText(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const normalized = value.replace(/\s+/g, " ").trim();
  if (normalized.length === 0 || normalized.length > 120) return null;
  return normalized;
}

function getFirstSourceText(...values: unknown[]): string | null {
  for (const value of values) {
    const text = normalizeSourceText(value);
    if (text !== null) return text;
  }
  return null;
}

function getNestedNativeAppIdentifier(value: unknown): string | null {
  const record = asRecord(value);
  if (!record) return null;
  return getFirstSourceText(
    record.bundleIdentifier,
    record.bundle_identifier,
    record.bundleId,
    record.bundle_id,
  );
}

function getNestedNativeAppDisplayName(value: unknown): string | null {
  const record = asRecord(value);
  if (!record) return null;
  return getFirstSourceText(
    record.displayName,
    record.display_name,
    record.appName,
    record.app_name,
    record.name,
    record.title,
    record.bundleIdentifier,
    record.bundle_identifier,
    record.bundleId,
    record.bundle_id,
  );
}

function isNativeAppIdentifier(value: string, platform: CodexMcpVisualSourcePlatform): boolean {
  const trimmed = value.trim();
  if (platform !== "windows") return MACOS_NATIVE_APP_IDENTIFIER_PATTERN.test(trimmed);
  return (
    MACOS_NATIVE_APP_IDENTIFIER_PATTERN.test(trimmed) ||
    WINDOWS_NATIVE_APP_PROCESS_PATTERN.test(trimmed) ||
    WINDOWS_NATIVE_APP_EXE_PATTERN.test(trimmed) ||
    WINDOWS_NATIVE_APP_UWP_PATTERN.test(trimmed) ||
    WINDOWS_NATIVE_APP_DOTTED_EXE_PATTERN.test(trimmed) ||
    WINDOWS_AUTOGENERATED_APP_PATTERN.test(trimmed)
  );
}

function resolveComputerUseNativeAppIdentifier(
  value: unknown,
  platform: CodexMcpVisualSourcePlatform,
): string | null {
  const args = asRecord(value);
  if (!args) return null;

  const candidate = getFirstSourceText(
    typeof args.app === "string" ? args.app : getNestedNativeAppIdentifier(args.app),
    getNestedNativeAppIdentifier(args.currentApp),
    getNestedNativeAppIdentifier(args.current_app),
    args.bundleIdentifier,
    args.bundle_identifier,
    args.bundleId,
    args.bundle_id,
  );
  return candidate !== null && isNativeAppIdentifier(candidate, platform) ? candidate : null;
}

function resolveComputerUseNativeAppDisplayName(
  value: unknown,
  platform: CodexMcpVisualSourcePlatform,
): string | null {
  const args = asRecord(value);
  if (!args) return null;

  const candidate = getFirstSourceText(
    typeof args.app === "string" ? args.app : getNestedNativeAppDisplayName(args.app),
    getNestedNativeAppDisplayName(args.currentApp),
    getNestedNativeAppDisplayName(args.current_app),
    args.targetAppName,
    args.target_app_name,
    args.appName,
    args.app_name,
    args.bundleIdentifier,
    args.bundle_identifier,
    args.bundleId,
    args.bundle_id,
    args.displayName,
    args.display_name,
  );
  return candidate !== null && !isNativeAppIdentifier(candidate, platform) ? candidate : null;
}

function resolveComputerUseNativeAppReference(input: {
  invocation: CodexMcpToolCallView["invocation"];
  platform: CodexMcpVisualSourcePlatform;
  source: CodexMcpToolCallSource | null;
}): CodexMcpVisualSource["nativeAppReference"] {
  if (input.source?.kind === "computerUse") return input.source.app;
  if (input.invocation.server !== COMPUTER_USE_SOURCE_KEY) return null;

  const appId = resolveComputerUseNativeAppIdentifier(input.invocation.arguments, input.platform);
  if (appId !== null) return { kind: "appId", appId };

  const displayName = resolveComputerUseNativeAppDisplayName(
    input.invocation.arguments,
    input.platform,
  );
  return displayName === null ? null : { kind: "displayName", displayName };
}

function getNativeAppReferenceName(
  reference: NonNullable<CodexMcpVisualSource["nativeAppReference"]>,
): string {
  return reference.kind === "appId" ? reference.appId : reference.displayName;
}

function isChromeNativeAppReference(
  reference: NonNullable<CodexMcpVisualSource["nativeAppReference"]>,
): boolean {
  if (reference.kind === "appId") {
    return (
      reference.appId === CHROME_BUNDLE_ID ||
      reference.appId === CHROME_NAME ||
      CHROME_PROCESS_PATTERN.test(reference.appId)
    );
  }
  return (
    reference.displayName === CHROME_DISPLAY_NAME ||
    reference.displayName.trim().toLowerCase() === "chrome"
  );
}

function formatSourceWord(word: string, index: number, style: "title" | "sentence"): string {
  const upper = word.toUpperCase();
  if (SOURCE_ACRONYMS.has(upper)) return upper;
  if (word.toLowerCase().endsWith("s")) {
    const singularUpper = word.slice(0, -1).toUpperCase();
    if (SOURCE_ACRONYMS.has(singularUpper)) return `${singularUpper}s`;
  }

  const lower = word.toLowerCase();
  const branded = SOURCE_BRANDS.get(lower);
  if (branded !== undefined) return branded;
  if (style === "sentence" && index > 0) return lower;
  if (index > 0 && SOURCE_LOWERCASE_TITLE_WORDS.has(lower)) return lower;
  return `${lower.slice(0, 1).toUpperCase()}${lower.slice(1)}`;
}

export function formatCodexMcpVisualSourceName(
  value: string,
  options: { style?: "title" | "sentence" } = {},
): string {
  return value
    .replace(/[_-]+/g, " ")
    .split(/\s+/)
    .filter((part) => part.length > 0)
    .map((word, index) => formatSourceWord(word, index, options.style ?? "title"))
    .join(" ");
}

function tokenizeMcpAppAlias(value: string): string[] {
  return value
    .trim()
    .toLowerCase()
    .split(/[^a-z0-9]+/g)
    .filter((part) => part.length > 0);
}

function tokenSequencesEqual(left: readonly string[], right: readonly string[]): boolean {
  return left.length === right.length && left.every((part, index) => part === right[index]);
}

function tokenSequenceStartsWith(value: readonly string[], prefix: readonly string[]): boolean {
  return (
    prefix.length > 0 &&
    value.length >= prefix.length &&
    prefix.every((part, index) => part === value[index])
  );
}

function getMcpAppAliases(app: ProtocolAppInfo): string[][] {
  const aliases = [
    tokenizeMcpAppAlias(app.name),
    tokenizeMcpAppAlias(app.id),
    tokenizeMcpAppAlias(app.id.replace(/^connector[_-]/i, "")),
    ...app.pluginDisplayNames.map(tokenizeMcpAppAlias),
  ];
  return aliases.filter(
    (alias, index) =>
      alias.length > 0 &&
      aliases.findIndex((candidate) => tokenSequencesEqual(candidate, alias)) === index,
  );
}

/**
 * Resolve the app identity attached to an MCP invocation.
 *
 * Tool activity labels, icons, summaries, and standalone rows must all use
 * this matcher. Keeping app identity late-bound avoids baking an app-list
 * snapshot into canonical conversation state.
 */
export function resolveCodexMcpAppInfo(input: {
  functionName: string;
  invocation: CodexMcpToolCallView["invocation"];
  resolvedApps: readonly ProtocolAppInfo[];
}): ProtocolAppInfo | null {
  const serverTokens = tokenizeMcpAppAlias(input.invocation.server);
  const toolTokens = tokenizeMcpAppAlias(input.invocation.tool);
  const functionTokenSequences = input.functionName
    .split("__")
    .map(tokenizeMcpAppAlias)
    .filter((tokens) => tokens.length > 0);

  for (const app of input.resolvedApps) {
    const aliases = getMcpAppAliases(app);
    const matches =
      aliases.some((alias) => tokenSequencesEqual(alias, serverTokens)) ||
      aliases.some((alias) => tokenSequenceStartsWith(toolTokens, alias)) ||
      functionTokenSequences.some((tokens) =>
        aliases.some((alias) => tokenSequenceStartsWith(tokens, alias)),
      );
    if (matches) return app;
  }
  return null;
}

function resolveSpecialMcpVisualSource(input: {
  invocation: CodexMcpToolCallView["invocation"];
  platform: CodexMcpVisualSourcePlatform;
  source: CodexMcpToolCallSource | null;
}): CodexMcpVisualSource | null {
  const nativeAppReference = resolveComputerUseNativeAppReference(input);
  if (nativeAppReference !== null) {
    const nativeAppName = getNativeAppReferenceName(nativeAppReference);
    const isChrome = isChromeNativeAppReference(nativeAppReference);
    return {
      key: isChrome ? "native-app:chrome" : `native-app:${nativeAppName}`,
      logoUrl: null,
      logoUrlDark: null,
      name: isChrome ? CHROME_NAME : formatCodexMcpVisualSourceName(nativeAppName),
      nativeAppReference,
    };
  }

  if (input.source?.kind === "browserUse") {
    const isChrome = input.source.backend === "chrome";
    return {
      key: isChrome ? "browser-use:chrome" : BROWSER_USE_SOURCE_KEY,
      logoUrl: isChrome ? CODEX_BROWSER_USE_CHROME_LOGO_DATA_URL : null,
      logoUrlDark: null,
      name: isChrome ? CHROME_NAME : BROWSER_USE_SOURCE_KEY,
      nativeAppReference: null,
    };
  }

  if (input.source?.kind === "computerUse" || input.invocation.server === COMPUTER_USE_SOURCE_KEY) {
    return {
      key: COMPUTER_USE_SOURCE_KEY,
      logoUrl: null,
      logoUrlDark: null,
      name: formatCodexMcpVisualSourceName(COMPUTER_USE_SOURCE_KEY),
      nativeAppReference: null,
    };
  }
  return null;
}

/** Exact late MCP visual identity projection shared by leaf, group, and summary views. */
export function resolveCodexMcpVisualSource(input: {
  functionName: string;
  invocation: CodexMcpToolCallView["invocation"];
  resolvedApps: readonly ProtocolAppInfo[];
  source: CodexMcpToolCallSource | null;
  platform?: CodexMcpVisualSourcePlatform;
}): CodexMcpVisualSource | null {
  const specialSource = resolveSpecialMcpVisualSource({
    invocation: input.invocation,
    platform: input.platform ?? detectMcpVisualSourcePlatform(),
    source: input.source,
  });
  if (specialSource !== null) return specialSource;

  const app = resolveCodexMcpAppInfo(input);
  if (app !== null) {
    return {
      key: `app:${app.id}`,
      logoUrl: app.logoUrl ?? null,
      logoUrlDark: app.logoUrlDark ?? null,
      name: app.name,
      nativeAppReference: null,
    };
  }

  const server = input.invocation.server.trim();
  if (server.length === 0) return null;
  return {
    key: `server:${server}`,
    logoUrl: null,
    logoUrlDark: null,
    name: formatCodexMcpVisualSourceName(server),
    nativeAppReference: null,
  };
}

export function resolveCodexMcpToolCallSource(
  serverName: string,
  resultMeta: ProtocolMcpToolCallResult["_meta"] | null,
): CodexMcpToolCallSource | null {
  if (!isCodexBrowserMcpServer(serverName)) return null;

  const meta = asRecord(resultMeta);
  const surface = asRecord(meta?.["codex/toolSurface"]);
  if (!surface) return null;

  if (
    surface.kind === "browserUse" &&
    (surface.backend === "chrome" || surface.backend === "iab" || surface.backend === "cdp")
  ) {
    return { kind: "browserUse", backend: surface.backend };
  }

  if (surface.kind !== "computerUse" || !("app" in surface)) return null;
  const app = normalizeComputerUseApp(surface.app);
  return app === undefined ? null : { kind: "computerUse", app };
}

export function projectCodexMcpToolCall(
  item: ProtocolMcpToolCallItem,
  turnStatus: TurnStatus,
): CodexMcpToolCallView {
  return completeCodexMcpToolCallForTurn(
    {
      callId: item.id,
      functionName: `${item.server}__${item.tool}`,
      mcpAppResourceUri: item.appContext?.resourceUri ?? item.mcpAppResourceUri,
      pluginId: item.pluginId,
      readOnlyHint: item.readOnlyHint,
      source: resolveCodexMcpToolCallSource(item.server, item.result?._meta ?? null),
      invocation: {
        server: item.server,
        tool: item.tool,
        arguments: item.arguments,
      },
      result: projectCodexMcpToolCallResult(item.result, item.error),
      durationMs: item.durationMs,
      completed: item.status !== "inProgress",
    },
    turnStatus,
  );
}

export function completeCodexMcpToolCallForTurn(
  payload: CodexMcpToolCallView,
  turnStatus: TurnStatus,
): CodexMcpToolCallView {
  if (payload.completed || turnStatus === "inProgress") return payload;
  return {
    ...payload,
    completed: true,
  };
}

export function resolveCodexMcpResourceUriFromMetadata(meta: unknown): string | null {
  const record = asRecord(meta);
  if (!record) return null;

  const outputTemplate = record["openai/outputTemplate"];
  if (
    outputTemplate !== undefined &&
    outputTemplate !== null &&
    typeof outputTemplate !== "string"
  ) {
    return null;
  }

  const flatResourceUri = record["ui/resourceUri"];
  if (flatResourceUri !== undefined && typeof flatResourceUri !== "string") return null;

  const rawUi = record.ui;
  if (rawUi !== undefined) {
    const ui = asRecord(rawUi);
    if (!ui) return null;
    const nestedResourceUri = ui.resourceUri;
    if (nestedResourceUri !== undefined && typeof nestedResourceUri !== "string") return null;
    if (nestedResourceUri !== undefined) return nestedResourceUri;
  }

  if (flatResourceUri !== undefined) return flatResourceUri;
  return typeof outputTemplate === "string" ? outputTemplate : null;
}

function resolveToolMetadata(
  payload: CodexMcpToolCallView,
  statuses: ProtocolListMcpServerStatusResponse | null,
): unknown {
  if (!statuses) return null;

  const server = statuses.data.find((entry) => entry.name === payload.invocation.server);
  const directTool = server?.tools[payload.invocation.tool];
  const directMetadata = directTool?._meta;
  if (directMetadata !== undefined && directMetadata !== null) return directMetadata;

  return (
    Object.values(server?.tools ?? {}).find((tool) => tool?.name === payload.invocation.tool)
      ?._meta ?? null
  );
}

export function resolveCodexMcpAppResourceMetadata(input: {
  payload: CodexMcpToolCallView;
  mcpServerStatuses: ProtocolListMcpServerStatusResponse | null;
}): { resourceUri: string } | null {
  const toolResourceUri = resolveCodexMcpResourceUriFromMetadata(
    resolveToolMetadata(input.payload, input.mcpServerStatuses),
  );
  if (toolResourceUri !== null) return { resourceUri: toolResourceUri };

  const resultMeta =
    input.payload.result?.type === "success" ? input.payload.result.raw._meta : null;
  const resultResourceUri = resolveCodexMcpResourceUriFromMetadata(resultMeta);
  return resultResourceUri === null ? null : { resourceUri: resultResourceUri };
}

export type CodexMcpAppClassification = "mcp-app" | "maybe-mcp-app" | "not-mcp-app";

/** Exact three-state MCP app resolver shared by activity classification and MCP app rendering. */
export function resolveCodexMcpAppClassification(input: {
  payload: CodexMcpToolCallView;
  mcpServerStatuses: ProtocolListMcpServerStatusResponse | null;
  isMcpAppWidgetSuperseded?: boolean;
}): CodexMcpAppClassification {
  if (input.isMcpAppWidgetSuperseded === true) return "not-mcp-app";

  const hasResolvedResource =
    input.payload.mcpAppResourceUri != null || resolveCodexMcpAppResourceMetadata(input) != null;
  if (hasResolvedResource) return "mcp-app";

  const successfulResult =
    input.payload.result?.type === "success" ? input.payload.result.raw : null;
  if (successfulResult == null) return "not-mcp-app";
  return input.mcpServerStatuses == null ? "maybe-mcp-app" : "not-mcp-app";
}
